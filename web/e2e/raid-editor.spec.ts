import {test,expect} from './fixtures.ts'
test.beforeEach(async({page})=>{await page.addInitScript(()=>localStorage.setItem('desertod.language','ru'))})

test('editable boss preview launches the exact configured event once and fits the menu',async({page})=>{
 await page.goto('/e2e/raid-editor-harness.html')
 await page.getByRole('button',{name:'БОСС-ФАЙТ',exact:true}).click()
 await page.getByLabel('Расчёт силы').selectOption('manual')
 await page.getByLabel('Здоровье ×',{exact:true}).fill('3')
 await expect(page.getByRole('button',{name:'Объявить набег'})).toHaveCount(0)
 await page.getByRole('button',{name:'Предпросмотр',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('Будет в каждой волне: 2')
 await expect(page.getByRole('status')).toContainText('Босс × 2')
 await expect(page.getByRole('status')).toContainText('Ручной эксперимент')
 await page.getByLabel('Здоровье ×',{exact:true}).fill('4')
 await expect(page.getByRole('button',{name:'Объявить набег'})).toHaveCount(0)
 await page.getByRole('button',{name:'Предпросмотр',exact:true}).click()
 await page.getByRole('button',{name:'Объявить набег'}).click()
 const launches=await page.evaluate(()=>(window as unknown as {raidEditorStand:{launches:{requestId:string;settings:{healthMultiplier:number;preset:string}}[]}}).raidEditorStand.launches)
 expect(launches).toHaveLength(1);expect(launches[0].settings.healthMultiplier).toBe(4);expect(launches[0].settings.preset).toBe('boss');expect(launches[0].requestId).toBeTruthy()
 const fits=await page.locator('.raid-editor').evaluate(el=>{const b=el.getBoundingClientRect();return b.left>=0&&b.right<=innerWidth})
 expect(fits).toBe(true)
 await page.screenshot({path:test.info().outputPath('raid-editor.png')})
})

test('custom presets retain edited composition and update without duplicates',async({page})=>{
 await page.goto('/e2e/raid-editor-harness.html')
 await page.getByRole('button',{name:'Орда',exact:true}).click()
 await page.getByLabel('Врагов в волне (максимум в авто)').fill('32')
 await page.getByRole('textbox',{name:'Название пресета'}).fill('Проверочная орда')
 await page.getByRole('button',{name:'Сохранить',exact:true}).click()
 await expect(page.getByLabel('Сохранённые пресеты')).toHaveValue('saved-1')
 await page.getByLabel('Врагов в волне (максимум в авто)').fill('16')
 await page.getByRole('button',{name:'Сохранить',exact:true}).click()
 await expect(page.getByLabel('Сохранённые пресеты').locator('option')).toHaveCount(2)
 await page.getByRole('button',{name:'БОСС-ФАЙТ',exact:true}).click()
 await page.getByLabel('Сохранённые пресеты').selectOption('saved-1')
 await expect(page.getByLabel('Врагов в волне (максимум в авто)')).toHaveValue('16')
 await page.getByRole('button',{name:'Предпросмотр',exact:true}).click()
 await expect(page.getByRole('status')).toContainText('Будет в каждой волне: 3')
 const fits=await page.locator('.raid-editor input,.raid-editor select,.raid-editor button').evaluateAll(els=>els.filter(el=>!!el.getClientRects().length).every(el=>{const b=el.getBoundingClientRect();return b.left>=0&&b.right<=innerWidth+1}))
 expect(fits).toBe(true)
})
