test('quick raid needs no advanced fields and choosing easier clears custom multipliers',async({page})=>{
 await page.goto('/e2e/raid-editor-harness.html')
 await expect(page.getByLabel('Здоровье ×',{exact:true})).not.toBeVisible()
 await page.getByLabel('Сложность',{exact:true}).selectOption('0.75')
 await page.getByRole('button',{name:'Предпросмотр',exact:true}).click()
 await expect(page.getByRole('button',{name:'Объявить набег'})).toBeVisible()
 await page.getByText('Дополнительные настройки',{exact:true}).click()
 await page.getByLabel('Здоровье ×',{exact:true}).fill('4')
 await expect(page.getByLabel('Сложность',{exact:true})).toHaveValue('custom')
 await page.getByLabel('Сложность',{exact:true}).selectOption('0.75')
 await expect(page.getByLabel('Здоровье ×',{exact:true})).toHaveValue('1')
 await page.getByRole('button',{name:'Предпросмотр',exact:true}).click()
 const settings=await page.evaluate(()=>(window as unknown as {raidEditorStand:{previews:{budgetMultiplier:number;healthMultiplier:number;mode:string}[]}}).raidEditorStand.previews.at(-1))
 expect(settings).toMatchObject({budgetMultiplier:.75,healthMultiplier:1,mode:'automatic'})
})

test('selecting several species always shares 100 percent and invalid manual shares never call preview',async({page})=>{
 await page.goto('/e2e/raid-editor-harness.html')
 await page.getByText('Дополнительные настройки',{exact:true}).click()
 await page.getByText('Состав, волны и ограничения',{exact:true}).click()
 await page.getByRole('checkbox',{name:'Волк',exact:true}).check()
 await page.getByRole('checkbox',{name:'Упырь',exact:true}).check()
 await expect(page.getByLabel('Волк %',{exact:true})).toHaveValue('50')
 await expect(page.getByLabel('Упырь %',{exact:true})).toHaveValue('50')
 await page.getByRole('checkbox',{name:'Скелет',exact:true}).check()
 const inputs=page.locator('.raid-editor-species input[type=number]')
 expect(await inputs.evaluateAll(els=>els.reduce((sum,e)=>sum+Number((e as HTMLInputElement).value),0))).toBe(100)
 await page.getByLabel('Упырь %',{exact:true}).fill('99')
 await page.getByRole('button',{name:'Предпросмотр',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('нужно 100%')
 expect(await page.evaluate(()=>(window as unknown as {raidEditorStand:{previews:unknown[]}}).raidEditorStand.previews.length)).toBe(0)
 await page.getByRole('button',{name:'Поровну',exact:true}).click()
 await page.getByRole('button',{name:'Предпросмотр',exact:true}).click()
 await expect(page.getByRole('button',{name:'Объявить набег'})).toBeVisible()
 await page.getByRole('checkbox',{name:'Скелет',exact:true}).uncheck()
 await expect(page.getByLabel('Волк %',{exact:true})).toHaveValue('50')
 await expect(page.getByLabel('Упырь %',{exact:true})).toHaveValue('50')
})

test('range and mixed-strength errors identify fields and block save as well as preview',async({page})=>{
 await page.goto('/e2e/raid-editor-harness.html')
 await page.getByText('Дополнительные настройки',{exact:true}).click()
 await page.getByLabel('Урон игрокам ×',{exact:true}).fill('11')
 await page.getByRole('textbox',{name:'Название пресета'}).fill('Ошибочный')
 await page.getByRole('button',{name:'Сохранить',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('Урон игрокам ×: от 0.25 до 10.')
 await expect(page.getByLabel('Урон игрокам ×',{exact:true})).toHaveAttribute('aria-invalid','true')
 await expect(page.getByLabel('Сохранённые пресеты').locator('option')).toHaveCount(1)
 await page.getByLabel('Урон игрокам ×',{exact:true}).fill('4')
 await page.getByText('Состав, волны и ограничения',{exact:true}).click()
 await page.getByLabel('Слабых, %',{exact:true}).fill('90')
 await page.getByLabel('Сильных, %',{exact:true}).fill('30')
 await page.getByRole('button',{name:'Предпросмотр',exact:true}).click()
 await expect(page.getByRole('alert')).toContainText('Слабых и сильных вместе больше 100%')
 await page.getByLabel('Слабых, %',{exact:true}).fill('60')
 await page.getByRole('button',{name:'Предпросмотр',exact:true}).click()
 await expect(page.getByRole('button',{name:'Объявить набег'})).toBeVisible()
})
