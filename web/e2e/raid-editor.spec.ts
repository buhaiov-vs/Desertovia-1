async function slide(control:Locator,value:number){
 const current=await control.evaluate(el=>{const input=el as HTMLInputElement;return {value:Number(input.value),step:Number(input.step)||1}})
 await control.focus()
 const steps=Math.round((value-current.value)/current.step)
 for(let n=0;n<Math.abs(steps);n++)await control.press(steps>0?'ArrowRight':'ArrowLeft')
 await expect(control).toHaveValue(String(value))
}
