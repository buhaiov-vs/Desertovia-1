import {test,expect} from './fixtures.ts'
for(const role of ['tsar','governor'])for(const width of [320,390,1280])test(`menu stays one row and returns to map without navigation for ${role} at ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:width===1280?720:844})
 await page.addInitScript(()=>localStorage.setItem('desertod.language','ru'))
 await page.goto('/e2e/mobile-menu-harness.html?role='+role)
 const tabs=page.locator('.modal.menu .tabs'), buttons=tabs.locator('button')
 await expect(buttons).toHaveCount(role==='tsar'?4:6)
 const tops=await buttons.evaluateAll(nodes=>nodes.map(n=>n.getBoundingClientRect().top))
 expect(Math.max(...tops)-Math.min(...tops)).toBeLessThan(2)
 expect(await page.locator('.modal.menu').evaluate(n=>n.scrollWidth<=n.clientWidth)).toBe(true)
 await expect(page.getByRole('checkbox',{name:'Показывать ники игроков на карте'})).toBeChecked()
 await page.getByRole('checkbox',{name:'Показывать ники игроков на карте'}).uncheck()
 expect(await page.evaluate(()=>localStorage.getItem('desertovia.playerNames'))).toBe('0')
 const url=page.url();await page.getByRole('button',{name:'Вернуться к карте'}).click()
 await expect(page.locator('.modal.menu')).toHaveCount(0);expect(page.url()).toBe(url)
 const dock=page.locator('.hud-buttons')
 const rects=await dock.locator('button').evaluateAll(nodes=>nodes.map(n=>{const r=n.getBoundingClientRect();return {x:r.x,y:r.y,right:r.right}}))
 expect(Math.max(...rects.map(r=>r.y))-Math.min(...rects.map(r=>r.y))).toBeLessThan(2)
 for(const r of rects){expect(r.x).toBeGreaterThanOrEqual(0);expect(r.right).toBeLessThanOrEqual(width)}
 await page.screenshot({path:test.info().outputPath(`dock-${width}.png`)})
})
test('chat hides work spam by default and groups repeated reports when enabled',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.addInitScript(()=>{localStorage.setItem('desertod.language','ru');localStorage.setItem('desertod.chat.mode','full')})
 await page.goto('/e2e/chat-harness.html')
 await expect(page.locator('.chat-line.activity')).toHaveCount(0)
 await page.getByRole('button',{name:'События',exact:true}).click()
 await expect(page.locator('.chat-line.activity')).toHaveCount(1)
 await expect(page.locator('.chat-line.activity')).toContainText('×8')
 await expect(page.locator('.chat-line.message')).toHaveCount(70)
})
