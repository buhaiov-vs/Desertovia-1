 const fits=await page.locator('.raid-editor input,.raid-editor select,.raid-editor button').evaluateAll(els=>els.filter(el=>!!el.getClientRects().length).every(el=>{const b=el.getBoundingClientRect();return b.left>=0&&b.right<=innerWidth+1}))
 expect(fits).toBe(true)
